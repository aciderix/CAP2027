INSERT INTO theme_keywords (theme_id, keyword)
SELECT t.id, n.kw
FROM new_kw n
JOIN themes t ON t.slug = n.slug
WHERE NOT EXISTS (
  SELECT 1 FROM theme_keywords k
  WHERE k.theme_id = t.id AND lower(k.keyword) = lower(n.kw)
);
